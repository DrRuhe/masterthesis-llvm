#!/usr/bin/env python3
"""Generate a machine-readable SBOM for the Nix devshell.

This script produces three files:
  - devshell_sbom.json
  - devshell_sbom.tsv
  - devshell_sbom.typ

The Typst file is intended for inclusion from the thesis appendix.
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
from pathlib import Path


NAME_VERSION_RE = re.compile(r"^(?P<name>.+)-(?P<version>[0-9][A-Za-z0-9.+:_-]*)$")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--flake",
        default=str((Path(__file__).resolve().parents[4] / "flake.nix").resolve().parent),
        help="Path to the flake root (default: project root).",
    )
    parser.add_argument(
        "--output-dir",
        default=str((Path(__file__).resolve().parents[1] / "reports" / "thesis-appendix").resolve()),
        help="Directory for generated SBOM artifacts.",
    )
    parser.add_argument(
        "--system",
        default="x86_64-linux",
        help="Nix system identifier (default: x86_64-linux).",
    )
    return parser.parse_args()


def run(cmd: list[str], cwd: Path) -> str:
    return subprocess.run(cmd, cwd=cwd, check=True, text=True, capture_output=True).stdout


def split_name_version(store_path: str) -> tuple[str, str]:
    stem = Path(store_path).name
    if "-" in stem:
        stem = stem.split("-", 1)[1]
    m = NAME_VERSION_RE.match(stem)
    if not m:
        return stem, ""
    return m.group("name"), m.group("version")


def escape_typst(text: str) -> str:
    return (
        text.replace("\\", "\\\\")
        .replace('"', '\\"')
    )


def main() -> None:
    args = parse_args()
    flake_root = Path(args.flake).resolve()
    output_dir = Path(args.output_dir).resolve()
    output_dir.mkdir(parents=True, exist_ok=True)

    attr = f".#devShells.{args.system}.default"
    out_path = run(
        ["nix", "build", attr, "--no-link", "--print-out-paths"],
        cwd=flake_root,
    ).strip()
    requisites = run(
        ["nix-store", "--query", "--requisites", out_path],
        cwd=flake_root,
    ).splitlines()

    records: list[dict[str, str]] = []
    for store_path in sorted(set(requisites)):
        name, version = split_name_version(store_path)
        records.append(
            {
                "name": name,
                "version": version,
                "store_path": store_path,
            }
        )

    json_path = output_dir / "devshell_sbom.json"
    tsv_path = output_dir / "devshell_sbom.tsv"
    typ_path = output_dir / "devshell_sbom.typ"

    json_path.write_text(json.dumps(records, indent=2) + "\n")

    with tsv_path.open("w") as f:
        f.write("name\tversion\tstore_path\n")
        for row in records:
            f.write(f"{row['name']}\t{row['version']}\t{row['store_path']}\n")

    lines = [
        "// Auto-generated by benchmarks/reporting/generate_devshell_sbom.py",
        f'#par([Nix devshell closure for `{escape_typst(attr)}` on `{escape_typst(args.system)}`.])',
        f'#par([Generated from `{escape_typst(str(flake_root))}`.])',
        f'#par([Total store paths: {len(records)}. For machine-readable formats see `devshell_sbom.json` and `devshell_sbom.tsv` in the same directory.])',
        '#text(size: 7pt)[',
    ]
    for row in records:
        pkg = escape_typst(row["name"])
        version = escape_typst(row["version"] or "?")
        store_path = escape_typst(row["store_path"])
        lines.append(f'- `{pkg}` {version}  `{store_path}`')
    lines.append(']')
    typ_path.write_text("\n".join(lines) + "\n")

    print(f"Wrote {json_path}")
    print(f"Wrote {tsv_path}")
    print(f"Wrote {typ_path}")


if __name__ == "__main__":
    main()
